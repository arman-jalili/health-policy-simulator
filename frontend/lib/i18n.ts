type EnumConcept = keyof typeof enumLabels;
type EnumValue<C extends EnumConcept> = keyof (typeof enumLabels)[C];

export function enumLabel<C extends EnumConcept>(
  concept: C,
  value: string | null | undefined,
  locale: Locale,
): string {
  if (value === null || value === undefined || value === "") return "—";
  const group = enumLabels[concept] as Labels;
  const entry = group[value];
  if (entry === undefined) return humanize(value);
  return locale === "en" ? entry.en : entry.de;
}

export function hasEnumLabel(concept: EnumConcept, value: string): boolean {
  return (enumLabels[concept] as Labels)[value] !== undefined;
}

export function humanize(value: string): string {
  return value
    .replace(/_/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

export function enumValues<C extends EnumConcept>(concept: C): readonly EnumValue<C>[] {
  return Object.keys(enumLabels[concept]) as EnumValue<C>[];
}

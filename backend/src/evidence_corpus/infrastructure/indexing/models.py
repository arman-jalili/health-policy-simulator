"""Search index tables: one row per indexed passage plus the published manifest.

Canonical: .pi/architecture/decisions/ADR-002-data-storage-strategy.md

`tsvector` is generated by PostgreSQL in the German configuration, so lexical search never depends
on application-side tokenisation. Embeddings live in a separate pgvector table (Phase 1 retrieval).
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import (
    Boolean,
    Computed,
    DateTime,
    Index,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from shared.db import Base


class IndexedPassage(Base):
    """A searchable passage: the citation target resolved by ``/passages/{id}``."""

    __tablename__ = "evidence_corpus_indexed_passage"
    __table_args__ = (
        Index(
            "ix_evidence_corpus_indexed_passage_tsv",
            "tsv",
            postgresql_using="gin",
        ),
        Index("ix_evidence_corpus_indexed_passage_document_id", "document_id"),
    )

    passage_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    document_id: Mapped[str] = mapped_column(String(64), nullable=False)
    article_id: Mapped[str] = mapped_column(String(64), nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    speaker_kind: Mapped[str] = mapped_column(String(16), nullable=False)
    citable: Mapped[bool] = mapped_column(Boolean, nullable=False)
    page_from: Mapped[int] = mapped_column(Integer, nullable=False)
    page_to: Mapped[int] = mapped_column(Integer, nullable=False)
    offset_start: Mapped[int] = mapped_column(Integer, nullable=False)
    offset_end: Mapped[int] = mapped_column(Integer, nullable=False)
    indexed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    tsv: Mapped[str] = mapped_column(
        TSVECTOR, Computed("to_tsvector('german', text)", persisted=True), nullable=False
    )


class IndexManifestRow(Base):
    """The published index state a snapshot resolves to."""

    __tablename__ = "evidence_corpus_index_manifest"

    index_version: Mapped[str] = mapped_column(String(80), primary_key=True)
    embedding_model: Mapped[str] = mapped_column(String(120), nullable=False)
    searchable_since: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    passage_count: Mapped[int] = mapped_column(Integer, nullable=False)
    is_current: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default="false")
